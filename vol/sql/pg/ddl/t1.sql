CREATE TABLE IF NOT EXISTS t1 (
  id INT NOT NULL,
  recorded_at TIMESTAMP NOT NULL,
  payload VARCHAR(255) NOT NULL,
  PRIMARY KEY (id, recorded_at)
) PARTITION BY RANGE (recorded_at);

CREATE TABLE t1_p_past   PARTITION OF t1 FOR VALUES FROM (MINVALUE)     TO ('2025-01-01');
CREATE TABLE t1_p_2025   PARTITION OF t1 FOR VALUES FROM ('2025-01-01') TO ('2026-01-01');
CREATE TABLE t1_p_2026   PARTITION OF t1 FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
CREATE TABLE t1_p_future PARTITION OF t1 FOR VALUES FROM ('2027-01-01') TO (MAXVALUE);

CREATE INDEX t1_payload_idx ON t1 (payload);
